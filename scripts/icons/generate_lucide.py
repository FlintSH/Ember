#!/usr/bin/env python3
"""Generate Compose ImageVectors from Lucide SVGs.

Flare's web interface uses Lucide icons. Ember uses the same set so both feel
like one product. Lucide is ISC licensed; see THIRD_PARTY_NOTICES.md.

Usage:
  npm pack lucide-static && tar -xzf lucide-static-*.tgz
  python3 scripts/icons/generate_lucide.py package/icons

The icon list lives in ICONS below. Output replaces
app/src/main/kotlin/dev/fl1nt/ember/ui/icons/Lucide.kt.
"""

import json
import pathlib
import re
import sys
import xml.etree.ElementTree as ET

ICONS = [
    "archive", "arrow-left", "arrow-up-right", "battery-charging", "bell", "bell-off",
    "book-open", "calendar-clock", "camera", "check", "chevron-down", "chevron-left",
    "chevron-right", "circle-alert", "circle-check", "circle-help", "circle-x", "clipboard",
    "clipboard-paste", "clock", "cloud-off", "cloud-upload", "copy", "ellipsis-vertical",
    "external-link", "eye", "eye-off", "file", "file-text", "file-up", "files", "folder",
    "folder-open", "folder-plus", "folder-sync", "globe", "hard-drive", "history", "house",
    "image", "image-up", "images", "info", "key-round", "layers", "link", "link-2",
    "list-filter", "loader-circle", "lock", "lock-open", "log-out", "monitor-smartphone",
    "moon", "music", "network", "palette", "pause", "play", "plus", "refresh-cw",
    "rotate-ccw", "scan-line", "search", "send", "server", "settings", "share-2",
    "shield-check", "sliders-horizontal", "smartphone", "sparkles", "sun", "sun-moon",
    "tag", "text-select", "timer", "trash-2", "triangle-alert", "upload", "video",
    "wifi", "wifi-off", "x", "zap",
]


def num(value):
    return float(value) if value is not None else 0.0


def fmt(value):
    text = f"{value:.4f}".rstrip("0").rstrip(".")
    return text if text not in ("-0", "") else "0"


def ellipse_path(cx, cy, rx, ry):
    return (
        f"M{fmt(cx - rx)} {fmt(cy)}"
        f"a{fmt(rx)} {fmt(ry)} 0 1 0 {fmt(2 * rx)} 0"
        f"a{fmt(rx)} {fmt(ry)} 0 1 0 {fmt(-2 * rx)} 0Z"
    )


def rect_path(x, y, w, h, rx, ry):
    if rx == 0 and ry == 0:
        return f"M{fmt(x)} {fmt(y)}h{fmt(w)}v{fmt(h)}h{fmt(-w)}Z"
    rx = min(rx, w / 2)
    ry = min(ry, h / 2)
    return (
        f"M{fmt(x + rx)} {fmt(y)}"
        f"h{fmt(w - 2 * rx)}a{fmt(rx)} {fmt(ry)} 0 0 1 {fmt(rx)} {fmt(ry)}"
        f"v{fmt(h - 2 * ry)}a{fmt(rx)} {fmt(ry)} 0 0 1 {fmt(-rx)} {fmt(ry)}"
        f"h{fmt(-(w - 2 * rx))}a{fmt(rx)} {fmt(ry)} 0 0 1 {fmt(-rx)} {fmt(-ry)}"
        f"v{fmt(-(h - 2 * ry))}a{fmt(rx)} {fmt(ry)} 0 0 1 {fmt(rx)} {fmt(-ry)}Z"
    )


def points_path(points, close):
    values = [float(v) for v in re.split(r"[\s,]+", points.strip()) if v]
    pairs = list(zip(values[0::2], values[1::2]))
    path = "M" + " L".join(f"{fmt(x)} {fmt(y)}" for x, y in pairs)
    return path + ("Z" if close else "")


def element_paths(element):
    tag = element.tag.split("}")[-1]
    a = element.attrib
    if tag == "path":
        return a["d"]
    if tag == "circle":
        r = num(a.get("r"))
        return ellipse_path(num(a.get("cx")), num(a.get("cy")), r, r)
    if tag == "ellipse":
        return ellipse_path(num(a.get("cx")), num(a.get("cy")), num(a.get("rx")), num(a.get("ry")))
    if tag == "rect":
        rx = a.get("rx")
        ry = a.get("ry")
        rx_v = num(rx if rx is not None else ry)
        ry_v = num(ry if ry is not None else rx)
        return rect_path(num(a.get("x")), num(a.get("y")), num(a.get("width")), num(a.get("height")), rx_v, ry_v)
    if tag == "line":
        return f"M{fmt(num(a.get('x1')))} {fmt(num(a.get('y1')))}L{fmt(num(a.get('x2')))} {fmt(num(a.get('y2')))}"
    if tag == "polyline":
        return points_path(a["points"], close=False)
    if tag == "polygon":
        return points_path(a["points"], close=True)
    raise ValueError(f"Unsupported element <{tag}>")


# XML drawables for places Compose can't draw: the Quick Settings tile and
# launcher shortcuts. Shortcut icons sit on a Flare navy circle.
XML_ICONS = {
    "ic_tile_paste": ("clipboard-paste", "tile"),
    "ic_shortcut_paste": ("file-text", "shortcut"),
    "ic_shortcut_link": ("link", "shortcut"),
    "ic_shortcut_upload": ("upload", "shortcut"),
    "ic_shortcut_sync": ("folder-sync", "shortcut"),
}


def xml_drawable(paths, style):
    lines = [
        '<?xml version="1.0" encoding="utf-8"?>',
        "<!-- Generated by scripts/icons/generate_lucide.py. Do not edit. -->",
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
    ]
    if style == "tile":
        lines += [
            '    android:width="24dp"',
            '    android:height="24dp"',
            '    android:viewportWidth="24"',
            '    android:viewportHeight="24">',
        ]
        group_open, group_close, color = "", "", "#FFFFFFFF"
    else:
        lines += [
            '    android:width="48dp"',
            '    android:height="48dp"',
            '    android:viewportWidth="48"',
            '    android:viewportHeight="48">',
            '    <path',
            '        android:fillColor="#FF020817"',
            '        android:pathData="M0,24a24,24 0,1 0,48 0a24,24 0,1 0,-48 0Z" />',
        ]
        group_open = '    <group android:scaleX="1" android:scaleY="1" android:translateX="12" android:translateY="12">'
        group_close = "    </group>"
        color = "#FFF8FAFC"
    if group_open:
        lines.append(group_open)
    for data, filled in paths:
        lines += [
            "        <path" if group_open else "    <path",
            f'            android:pathData="{data}"' if group_open else f'        android:pathData="{data}"',
        ]
        indent = "            " if group_open else "        "
        if filled:
            lines.append(f'{indent}android:fillColor="{color}"')
        lines += [
            f'{indent}android:strokeColor="{color}"',
            f'{indent}android:strokeWidth="2"',
            f'{indent}android:strokeLineCap="round"',
            f'{indent}android:strokeLineJoin="round" />',
        ]
    if group_close:
        lines.append(group_close)
    lines.append("</vector>")
    return "\n".join(lines) + "\n"


def icon_paths(source, icon):
    svg = ET.parse(source / f"{icon}.svg").getroot()
    paths = []
    for element in svg:
        tag = element.tag.split("}")[-1]
        if tag in ("title", "desc"):
            continue
        paths.append((element_paths(element), element.attrib.get("fill") == "currentColor"))
    return paths


def property_name(icon):
    return "".join(part.capitalize() for part in re.split(r"[-_]", icon) if part)


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    source = pathlib.Path(sys.argv[1])
    root = pathlib.Path(__file__).resolve().parents[2]
    output = root / "app/src/main/kotlin/dev/fl1nt/ember/ui/icons/Lucide.kt"
    version = "unknown"
    package_json = source.parent / "package.json"
    if package_json.exists():
        version = json.loads(package_json.read_text())["version"]

    lines = [
        "// Generated by scripts/icons/generate_lucide.py from lucide-static " + version + ". Do not edit.",
        "// Lucide is ISC licensed. See THIRD_PARTY_NOTICES.md.",
        "package dev.fl1nt.ember.ui.icons",
        "",
        "import androidx.compose.ui.graphics.vector.ImageVector",
        "",
        "/** The Lucide icons Ember uses, matching Flare's web interface. */",
        "object Lucide {",
    ]
    for icon in ICONS:
        paths = icon_paths(source, icon)
        args = ", ".join(('fill("' if filled else 'stroke("') + d + '")' for d, filled in paths)
        lines.append(f"    val {property_name(icon)}: ImageVector by lazy {{ lucide(\"{icon}\", {args}) }}")
    lines.append("}")
    lines.append("")
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n".join(lines))
    drawables = root / "app/src/main/res/drawable"
    for resource, (icon, style) in XML_ICONS.items():
        (drawables / f"{resource}.xml").write_text(xml_drawable(icon_paths(source, icon), style))
    print(f"Wrote {len(ICONS)} icons to {output.relative_to(root)} and {len(XML_ICONS)} drawables")


if __name__ == "__main__":
    main()
